let score = 15;
let age = 20;


// Check score
if (score >= 10) {
    console.log("Passed");
} else {
    console.log("Failed");
}


// Check age
if (age >= 18) {
    console.log("Adult");
} else {
    console.log("Minor");
}


// Combined condition
if (score >= 10 && age >= 18) {
    console.log("Adult and Passed");
} else {
    console.log("Condition not matched");
}